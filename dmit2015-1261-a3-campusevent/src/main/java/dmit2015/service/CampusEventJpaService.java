package dmit2015.service;

import dmit2015.model.CampusEvent;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.inject.Named;
import jakarta.persistence.EntityManager;
import jakarta.persistence.PersistenceContext;
import jakarta.transaction.Transactional;

import java.util.List;
import java.util.NoSuchElementException;
import java.util.Objects;
import java.util.Optional;

/**
 * Jakarta Persistence implementation of {@link CampusEventService}.
 * All EntityManager code for CampusEvent lives here, not in the JSF backing bean.
 */
@Named("jakartaPersistenceCampusEventService")
@ApplicationScoped
public class CampusEventJpaService implements CampusEventService {

    @PersistenceContext
    private EntityManager entityManager;

    @Override
    @Transactional
    public CampusEvent create(CampusEvent newEvent) {
        Objects.requireNonNull(newEvent, "CampusEvent to create must not be null");
        // The id is generated by the database identity column
        newEvent.setId(null);
        entityManager.persist(newEvent);
        return newEvent;
    }

    @Override
    public List<CampusEvent> getAllCampusEvents() {
        return entityManager.createQuery(
                        "SELECT e FROM CampusEvent e ORDER BY e.eventDate, e.id", CampusEvent.class)
                .getResultList();
    }

    @Override
    public Optional<CampusEvent> getCampusEventById(Long id) {
        Objects.requireNonNull(id, "id must not be null");
        return Optional.ofNullable(entityManager.find(CampusEvent.class, id));
    }

    @Override
    @Transactional
    public CampusEvent updateCampusEvent(CampusEvent existingEvent) {
        Objects.requireNonNull(existingEvent, "CampusEvent to update must not be null");
        Objects.requireNonNull(existingEvent.getId(), "CampusEvent id must not be null");

        CampusEvent storedEvent = getCampusEventById(existingEvent.getId())
                .orElseThrow(() -> new NoSuchElementException(
                        "Could not find CampusEvent with id: " + existingEvent.getId()));

        // Copy only the fields the user is allowed to edit
        storedEvent.setTitle(existingEvent.getTitle());
        storedEvent.setLocation(existingEvent.getLocation());
        storedEvent.setEventDate(existingEvent.getEventDate());
        storedEvent.setCategory(existingEvent.getCategory());
        storedEvent.setDescription(existingEvent.getDescription());
        storedEvent.setOrganizerName(existingEvent.getOrganizerName());

        return entityManager.merge(storedEvent);
    }

    @Override
    @Transactional
    public void deleteCampusEventById(Long id) {
        CampusEvent storedEvent = getCampusEventById(id)
                .orElseThrow(() -> new NoSuchElementException("Could not find CampusEvent with id: " + id));
        entityManager.remove(storedEvent);
    }
}
